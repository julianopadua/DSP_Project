def make_sample_window_from_beats(beat_samples, fs, start_beat_idx=1, n_beats=4, margin_s=0.25):
    chosen = beat_samples[start_beat_idx:start_beat_idx + n_beats]
    margin = int(round(margin_s * fs))
    start = max(0, int(chosen[0]) - margin)
    end = int(chosen[-1]) + margin
    return start, end, chosen


def full_beat_bounds(center_sample, fs, n_samples, pre_s=0.25, post_s=0.45):
    pre = int(round(pre_s * fs))
    post = int(round(post_s * fs))
    start = int(center_sample) - pre
    end = int(center_sample) + post
    if start < 0 or end > n_samples:
        return None
    return start, end


def rr_context(valid_samples, idx, fs):
    rr_prev = np.nan
    rr_next = np.nan
    if idx > 0:
        rr_prev = (valid_samples[idx] - valid_samples[idx - 1]) / fs
    if idx + 1 < len(valid_samples):
        rr_next = (valid_samples[idx + 1] - valid_samples[idx]) / fs
    return float(rr_prev), float(rr_next)

