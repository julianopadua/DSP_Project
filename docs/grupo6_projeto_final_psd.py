"""### 1.6.7 Filtros de Gabor 1D

Estas funções constroem os kernels de Gabor e calculam respostas locais. A parte par e a parte ímpar permitem formar uma energia local menos dependente da fase.
"""

def gabor_kernel(fs, f0_hz, sigma_s, phase=0.0, n_sigma=4.0):
    half = int(np.ceil(n_sigma * sigma_s * fs))
    t = np.arange(-half, half + 1) / fs
    envelope = np.exp(-(t ** 2) / (2.0 * sigma_s ** 2))
    h = envelope * np.cos(2.0 * np.pi * f0_hz * t + phase)
    h = h - np.mean(h)
    norm = np.sqrt(np.sum(h ** 2))
    if norm > 0:
        h = h / norm
    return t, h


def gabor_response_component(x, fs, f0_hz, sigma_s, component="even"):
    phase = 0.0 if component == "even" else np.pi / 2.0
    _, h = gabor_kernel(fs, f0_hz, sigma_s, phase=phase)
    return signal.fftconvolve(x, h, mode="same")


def gabor_energy_response(x, fs, f0_hz, sigma_s):
    even = gabor_response_component(x, fs, f0_hz, sigma_s, "even")
    odd = gabor_response_component(x, fs, f0_hz, sigma_s, "odd")
    return even ** 2 + odd ** 2


def gabor_component_response(x, fs, f0_hz, sigma_s, component="magnitude"):
    even = gabor_response_component(x, fs, f0_hz, sigma_s, "even")
    if component == "even":
        return even
    odd = gabor_response_component(x, fs, f0_hz, sigma_s, "odd")
    if component == "odd":
        return odd
    if component == "magnitude":
        return np.sqrt(even ** 2 + odd ** 2)
    raise ValueError("component deve ser 'even', 'odd' ou 'magnitude'")


def normalize_abs_response(response):
    values = np.abs(np.asarray(response, dtype=float))
    max_value = float(np.max(values)) if len(values) else 0.0
    return values / max(max_value, 1e-20)


def detect_gabor_wave_peaks(responses, ann_samples, fs, bank, n_samples):
    rows = []
    for beat_id, r_sample in enumerate(ann_samples, start=1):
        for wave, response in responses.items():
            spec = bank[wave]
            start_offset_s, end_offset_s = spec["window_s"]
            start = max(0, int(round(r_sample + start_offset_s * fs)))
            end = min(n_samples, int(round(r_sample + end_offset_s * fs)))
            if end <= start:
                continue

            local = np.abs(response[start:end]).copy()
            expected_offset_s = spec.get("expected_offset_s")
            prior_sigma_s = spec.get("prior_sigma_s")
            prior_weight = np.ones_like(local)
            if expected_offset_s is not None and prior_sigma_s is not None:
                indices = np.arange(start, end)
                offsets_s = (indices - r_sample) / fs
                prior_weight = np.exp(-0.5 * ((offsets_s - expected_offset_s) / prior_sigma_s) ** 2)
                local = local * prior_weight

            local_peak = int(np.argmax(local))
            peak = start + local_peak
            rows.append({
                "batimento": beat_id,
                "onda": wave,
                "tempo_s": float(peak / fs),
                "offset_do_r_ms": float(1000.0 * (peak - r_sample) / fs),
                "resposta_abs": float(np.abs(response[peak])),
                "peso_prior": float(prior_weight[local_peak]),
                "score": float(local[local_peak]),
            })
    return pd.DataFrame(rows)


def evaluate_gabor_parameter_grid(x, fs, ann_samples, wave_specs, f0_values, sigma_values):
    rows = []
    for wave, spec in wave_specs.items():
        qrs_window = (-0.06, 0.08)
        for f0_hz in f0_values:
            for sigma_s in sigma_values:
                response = gabor_component_response(x, fs, f0_hz, sigma_s, spec["component"])
                peak_values = []
                qrs_values = []
                offsets_ms = []
                for r_sample in ann_samples:
                    start = max(0, int(round(r_sample + spec["window_s"][0] * fs)))
                    end = min(len(x), int(round(r_sample + spec["window_s"][1] * fs)))
                    if end <= start:
                        continue

                    local = np.abs(response[start:end]).copy()
                    expected_offset_s = spec.get("expected_offset_s")
                    prior_sigma_s = spec.get("prior_sigma_s")
                    if expected_offset_s is not None and prior_sigma_s is not None:
                        indices = np.arange(start, end)
                        offsets_s = (indices - r_sample) / fs
                        prior = np.exp(-0.5 * ((offsets_s - expected_offset_s) / prior_sigma_s) ** 2)
                        local = local * prior

                    peak = start + int(np.argmax(local))
                    peak_values.append(float(np.abs(response[peak])))
                    offsets_ms.append(float(1000.0 * (peak - r_sample) / fs))

                    qrs_start = max(0, int(round(r_sample + qrs_window[0] * fs)))
                    qrs_end = min(len(x), int(round(r_sample + qrs_window[1] * fs)))
                    if qrs_end > qrs_start:
                        qrs_values.append(float(np.max(np.abs(response[qrs_start:qrs_end]))))

                rows.append({
                    "onda": wave,
                    "componente": spec["component"],
                    "f0_hz": f0_hz,
                    "sigma_s": sigma_s,
                    "media_pico_janela": float(np.mean(peak_values)) if peak_values else np.nan,
                    "razao_janela_qrs": float(np.mean(peak_values) / max(np.mean(qrs_values), 1e-20)) if qrs_values else np.nan,
                    "media_offset_ms": float(np.mean(offsets_ms)) if offsets_ms else np.nan,
                    "std_offset_ms": float(np.std(offsets_ms)) if offsets_ms else np.nan,
                })
    return pd.DataFrame(rows)


