"""### 1.6.5 Convolução no tempo e por FFT

A função `linear_convolution_full_manual` é uma das funções centrais do trabalho, porque implementa o somatório da convolução sem chamar uma função pronta de convolução. A versão por FFT usa zero-padding para reproduzir a convolução linear.
"""

def linear_convolution_full_manual(x, h):
    x = np.asarray(x, dtype=float)
    h = np.asarray(h, dtype=float)
    y = np.zeros(len(x) + len(h) - 1, dtype=float)
    for n in range(len(y)):
        soma = 0.0
        k_min = max(0, n - (len(h) - 1))
        k_max = min(len(x) - 1, n)
        for k in range(k_min, k_max + 1):
            soma += x[k] * h[n - k]
        y[n] = soma
    return y


def same_from_full_convolution(y_full, len_x, len_h):
    start = (len_h - 1) // 2
    end = start + len_x
    return y_full[start:end]


def linear_convolution_same_manual(x, h):
    y_full = linear_convolution_full_manual(x, h)
    return same_from_full_convolution(y_full, len(x), len(h))


def fft_convolution_same_linear(x, h):
    x = np.asarray(x, dtype=float)
    h = np.asarray(h, dtype=float)
    n_linear = len(x) + len(h) - 1
    X = np.fft.rfft(x, n=n_linear)
    H = np.fft.rfft(h, n=n_linear)
    y_full = np.fft.irfft(X * H, n=n_linear)
    return same_from_full_convolution(y_full, len(x), len(h))


def fft_convolution_circular_wrong(x, h):
    x = np.asarray(x, dtype=float)
    h = np.asarray(h, dtype=float)
    X = np.fft.rfft(x, n=len(x))
    H = np.fft.rfft(h, n=len(x))
    return np.fft.irfft(X * H, n=len(x))


def mse(a, b):
    a = np.asarray(a, dtype=float)
    b = np.asarray(b, dtype=float)
    return float(np.mean((a - b) ** 2))

