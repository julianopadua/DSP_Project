"""### 1.6.8 STFT e descritores tempo-frequência

Estas funções calculam a STFT, exibem o espectrograma e resumem a distribuição de potência por centroide, largura de banda e energia por faixas.
"""

def stft_power(x, fs, window_s=0.25, overlap=0.85):
    nperseg = max(32, int(round(window_s * fs)))
    noverlap = int(round(overlap * nperseg))
    f, t, Z = signal.stft(
        x,
        fs=fs,
        window="hann",
        nperseg=nperseg,
        noverlap=noverlap,
        boundary=None,
        padded=False,
    )
    power = np.abs(Z) ** 2
    return f, t, power


def plot_stft(x, fs, title, max_freq=80.0):
    f, tt, power = stft_power(x, fs)
    mask = f <= max_freq
    fig, ax = plt.subplots(figsize=(12, 4))
    pcm = ax.pcolormesh(tt, f[mask], 10 * np.log10(power[mask] + 1e-20), shading="auto", cmap="magma")
    ax.set_title(title)
    ax.set_xlabel("Tempo (s)")
    ax.set_ylabel("Frequencia (Hz)")
    fig.colorbar(pcm, ax=ax, label="Potencia (dB)")
    fig.tight_layout()
    return fig, ax


def stft_descriptors(x, fs):
    f, _, power = stft_power(x, fs)
    freq_energy = np.sum(power, axis=1)
    weights = freq_energy / max(np.sum(freq_energy), 1e-20)
    centroid = float(np.sum(f * weights))
    bandwidth = float(np.sqrt(np.sum(((f - centroid) ** 2) * weights)))
    return {
        "energia_total_stft": float(np.sum(power)),
        "centroide_hz": centroid,
        "largura_banda_hz": bandwidth,
        "energia_0p5_4": band_power(x, fs, 0.5, 4.0),
        "energia_4_8": band_power(x, fs, 4.0, 8.0),
        "energia_8_20": band_power(x, fs, 8.0, 20.0),
        "energia_20_40": band_power(x, fs, 20.0, 40.0),
    }

"""### 1.6.9 Extração de features por batimento

Estas funções transformam cada janela de batimento em uma linha tabular com features morfológicas, rítmicas, espectrais e de Gabor.
"""

def window_slice_by_seconds(values, fs, start_s, end_s, center_index=None):
    center = len(values) // 2 if center_index is None else int(np.clip(center_index, 0, len(values) - 1))
    lo = max(0, center + int(round(start_s * fs)))
    hi = min(len(values), center + int(round(end_s * fs)))
    return values[lo:hi]


def extract_morphology_features(beat, fs, r_index=None):
    x = np.asarray(beat, dtype=float)
    center = len(x) // 2 if r_index is None else int(np.clip(r_index, 0, len(x) - 1))
    diff = np.diff(x)
    return {
        "r_amp": float(x[center]),
        "beat_peak_to_peak": float(np.ptp(x)),
        "beat_energy": float(np.sum(x ** 2)),
        "beat_abs_area": float(np.sum(np.abs(x)) / fs),
        "beat_std": float(np.std(x)),
        "max_abs_slope": float(np.max(np.abs(diff)) * fs) if diff.size else 0.0,
    }


def extract_rr_features(rr_prev, rr_next):
    ratio = np.nan if not np.isfinite(rr_prev) or not np.isfinite(rr_next) or rr_next == 0 else rr_prev / rr_next
    return {"rr_prev_s": rr_prev, "rr_next_s": rr_next, "rr_ratio": ratio}


def extract_spectral_features(beat, fs):
    freqs, pxx = signal.welch(beat, fs=fs, nperseg=min(len(beat), 256))
    weights = pxx / max(np.sum(pxx), 1e-20)
    centroid = float(np.sum(freqs * weights))
    bandwidth = float(np.sqrt(np.sum(((freqs - centroid) ** 2) * weights)))
    return {
        "spectral_centroid_hz": centroid,
        "spectral_bandwidth_hz": bandwidth,
        "band_power_8_20": band_power(beat, fs, 8.0, 20.0),
        "band_power_20_40": band_power(beat, fs, 20.0, 40.0),
    }


def extract_gabor_features(beat, fs, r_index=None):
    features = {}
    configs = {
        "p": {"f0_hz": 8.0, "sigma_s": 0.110, "component": "even", "window": (-0.28, -0.07)},
        "qrs": {"f0_hz": 15.0, "sigma_s": 0.020, "component": "magnitude", "window": (-0.07, 0.07)},
        "t": {"f0_hz": 6.0, "sigma_s": 0.110, "component": "even", "window": (0.18, 0.45)},
    }
    for name, cfg in configs.items():
        start_s, end_s = cfg["window"]
        response = gabor_component_response(beat, fs, cfg["f0_hz"], cfg["sigma_s"], cfg["component"])
        segment = window_slice_by_seconds(response, fs, start_s, end_s, center_index=r_index)
        features[f"{name}_gabor_energy"] = float(np.sum(segment ** 2)) if len(segment) else 0.0
        features[f"{name}_gabor_max"] = float(np.max(np.abs(segment))) if len(segment) else 0.0
    return features


def extract_all_features(raw_beat, filtered_beat, fs, rr_prev, rr_next, r_index=None):
    features = {}
    features.update({f"raw_{k}": v for k, v in extract_morphology_features(raw_beat, fs, r_index=r_index).items()})
    features.update({f"filt_{k}": v for k, v in extract_morphology_features(filtered_beat, fs, r_index=r_index).items()})
    features.update(extract_rr_features(rr_prev, rr_next))
    features.update(extract_spectral_features(filtered_beat, fs))
    features.update(extract_gabor_features(filtered_beat, fs, r_index=r_index))
    return features

